"""
Reference Verifier Utilities
- Parse references from text
- Fuzzy match titles/authors
- Generate BibTeX entries
- Generate 4-level audit reports
"""

import re
import json
import unicodedata
from difflib import SequenceMatcher
from typing import Optional


# ── Text normalization and fuzzy matching ──────────────────────────────

def normalize_text(text: str) -> str:
    """Normalize text for comparison: lowercase, strip accents, remove punctuation."""
    text = text.lower().strip()
    text = unicodedata.normalize('NFKD', text)
    text = ''.join(c for c in text if not unicodedata.combining(c))
    text = re.sub(r'[^\w\s]', '', text)
    text = re.sub(r'\s+', ' ', text)
    return text


def fuzzy_match(s1: str, s2: str) -> float:
    """Return similarity ratio (0-1) between two strings."""
    return SequenceMatcher(None, normalize_text(s1), normalize_text(s2)).ratio()


def title_match(ref_title: str, db_title: str, threshold: float = 0.85) -> bool:
    """Check if two titles match above threshold."""
    return fuzzy_match(ref_title, db_title) >= threshold


def first_author_match(ref_authors: str, db_authors: str) -> bool:
    """Check if the first author's last name matches."""
    def extract_first_last(authors_str):
        authors_str = authors_str.strip()
        first_author = authors_str.split(',')[0].split(' and ')[0].strip()
        parts = first_author.split()
        if parts:
            return normalize_text(parts[0])
        return ""
    
    ref_last = extract_first_last(ref_authors)
    db_last = extract_first_last(db_authors)
    
    if not ref_last or not db_last:
        return False
    return ref_last == db_last or fuzzy_match(ref_last, db_last) > 0.8


